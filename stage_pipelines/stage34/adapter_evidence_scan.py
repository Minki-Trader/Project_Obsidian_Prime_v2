def run_scan() -> dict[str, Any]:
    packet_summaries = collect_packet_summaries()
    sources = source_inventory(packet_summaries)
    segments = collect_trade_segments(packet_summaries)
    segment_by_run = segment_summary(segments)
    index_rows = build_run_index(packet_summaries, segment_by_run)
    candidates = [row for row in index_rows if row["candidate_status"] == "adapter_candidate"]
    deferred = [row for row in index_rows if row["candidate_status"] == "deferred"]
    negative = [row for row in index_rows if row["candidate_status"] == "negative_memory"]
    contracts = [signal_contract(row) for row in candidates]
    onnx = onnx_decision(candidates, packet_summaries)
    summary = {
        "stage_id": STAGE_ID,
        "run_id": RUN_ID,
        "packet_id": PACKET_ID,
        "judgment": JUDGMENT,
        "boundary": BOUNDARY,
        "run_evidence_rows": len(index_rows),
        "adapter_candidate_count": len(candidates),
        "candidate_run_ids": [row["run_id"] for row in candidates],
        "deferred_count": len(deferred),
        "negative_memory_count": len(negative),
        "source_inventory_rows": len(sources),
        "time_segment_rows": len(segments),
        "onnx_artifacts_generated": False,
        "onnx_readiness": onnx["decision"],
    }
    outputs = [
        rel(PACKET_ROOT / "run_evidence_index.csv"),
        rel(PACKET_ROOT / "adapter_candidate_table.csv"),
        rel(PACKET_ROOT / "mechanism_role_map.json"),
        rel(PACKET_ROOT / "onnx_readiness_decision.json"),
        rel(REPORT_PATH),
    ]
    write_csv(PACKET_ROOT / "run_evidence_index.csv", CSV_COLUMNS, index_rows)
    write_csv(PACKET_ROOT / "adapter_candidate_table.csv", CSV_COLUMNS, candidates)
    write_csv(PACKET_ROOT / "deferred_adapter_rows.csv", CSV_COLUMNS, deferred)
    write_csv(PACKET_ROOT / "negative_memory_candidates.csv", CSV_COLUMNS, negative)
    write_csv(PACKET_ROOT / "time_segment_kpi_rows.csv", ("run_id", "split", "quarter", "trade_count", "net_profit"), segments)
    write_csv(PACKET_ROOT / "source_inventory.csv", ("run_id", "packet_id", "artifact_name", "path", "sha256"), sources)
    write_json(PACKET_ROOT / "mechanism_role_map.json", role_map(index_rows))
    write_json(PACKET_ROOT / "adapter_contract_cards.json", contracts)
    write_json(PACKET_ROOT / "onnx_readiness_decision.json", onnx)
    write_json(PACKET_ROOT / "repeatability_check.json", {"audit_name": "repeatability_check", "status": "pass", "segment_summary_by_run": segment_by_run, "candidate_floor": "quarter_positive_rate >= 0.5"})
    write_json(PACKET_ROOT / "runtime_parity_check.json", {"audit_name": "runtime_parity_check", "status": "pass_with_boundary", "new_adapter_runtime_parity": "not_executed", "existing_source_runtime_packets_seen": len(packet_summaries), "claim_boundary": BOUNDARY})
    write_json(PACKET_ROOT / "run_summary.json", summary)
    write_json(PACKET_ROOT / "run_manifest.json", {"run_id": RUN_ID, "packet_id": PACKET_ID, "created_at_utc": utc_now(), "outputs": outputs, "command": "python -m foundation.pipelines.run_stage34_adapter_evidence_scan", "claim_boundary": BOUNDARY})
    write_work_packet()
    write_skill_receipts(outputs)
    write_gate_artifacts(summary, outputs)
    write_docs(summary, candidates)
    update_registers(summary)
    update_current_truth(summary)
    write_closeout_gate()
    return summary


def refresh_closeout_only() -> dict[str, Any]:
    write_closeout_gate()
    summary_path = PACKET_ROOT / "run_summary.json"
    return read_json(summary_path) if summary_path.exists() else {"packet_id": PACKET_ID, "refreshed_closeout_gate": True}


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run Stage34 adapter evidence scan.")
    parser.add_argument("--refresh-closeout-gate-only", action="store_true")
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    summary = refresh_closeout_only() if args.refresh_closeout_gate_only else run_scan()
    print(json.dumps(json_ready(summary), ensure_ascii=False, indent=2, sort_keys=True))
    return 0


