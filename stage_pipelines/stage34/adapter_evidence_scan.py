def text_blob(*parts: Any) -> str:
    return " ".join(str(part or "") for part in parts).lower()


def derive_roles(blob: str) -> list[str]:
    roles: list[str] = []
    if re.search(r"runtime|mt5|onnx|handoff|score.table|package|native|parity", blob):
        roles.append("Runtime / Packaging")
    if re.search(r"permission|filter|abstain|abstention|calibration|block|flat|classifier", blob):
        roles.append("Permission / Filter / Abstention")
    if re.search(r"risk|tail|hazard|quantile|ngboost|drawdown|loss|distribution", blob):
        roles.append("Risk / Tail-risk")
    if re.search(r"survival|hold|exit|duration|time.to.event|lifecycle", blob):
        roles.append("Exit / Hold")
    if re.search(r"regime|hmm|markov|state|context|drift|session|volatility|trend|macro|gap|sequence|tcn", blob):
        roles.append("Regime / Context")
    if re.search(r"sizing|size|volume|lot", blob):
        roles.append("Sizing")
    if re.search(r"position|management|reversal|followthrough", blob):
        roles.append("Position Management")
    if re.search(r"entry|scout|logreg|lightgbm|extratrees|mlp|svm|lda|qda|xgb|catboost|ebm|gam|elasticnet|tabnet|model.family", blob):
        roles.append("Entry")
    if re.search(r"negative|invalid|blocked|inversion|failure|exhausted|missing|not_ready", blob):
        roles.append("Negative Memory")
    return [role for role in ROLES if role in roles] or ["Deferred"]


def mechanism_class(roles: Sequence[str], blob: str, onnx_seen: bool) -> str:
    if "Negative Memory" in roles and re.search(r"invalid|blocked|negative|failure|inversion", blob):
        return "negative_memory"
    if onnx_seen:
        return "onnx_runtime_adapter"
    if "Runtime / Packaging" in roles and re.search(r"score.table|handoff|mt5", blob):
        return "score_table_adapter"
    if "Permission / Filter / Abstention" in roles:
        return "permission_filter_adapter"
    if "Risk / Tail-risk" in roles:
        return "tail_risk_adapter"
    if "Exit / Hold" in roles:
        return "exit_hold_adapter"
    if "Regime / Context" in roles:
        return "regime_context_adapter"
    if "Entry" in roles:
        return "entry_score_adapter"
    return "deferred_adapter"


def collect_packet_summaries() -> dict[str, dict[str, Any]]:
    summaries: dict[str, dict[str, Any]] = {}
    for packet_dir in sorted((ROOT / "docs/agent_control/packets").iterdir()):
        if not packet_dir.is_dir():
            continue
        summary_path = packet_dir / "aggregate_summary.json"
        if not summary_path.exists():
            continue
        summary = read_json(summary_path)
        if not isinstance(summary, Mapping):
            continue
        stage_id = str(summary.get("stage_id") or "")
        run_id = packet_run_id(packet_dir.name, summary)
        if in_scope_stage(stage_id) or re.search(r"stage(1[0-9]|2[0-9]|3[0-2])", packet_dir.name):
            summaries[run_id] = {"packet_id": packet_dir.name, "packet_root": packet_dir, "summary": dict(summary)}
    return summaries


