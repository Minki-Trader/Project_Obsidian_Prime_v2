def collect_trade_segments(packet_summaries: Mapping[str, Mapping[str, Any]]) -> list[dict[str, Any]]:
    grouped: dict[tuple[str, str, str], dict[str, Any]] = {}
    for run_id, payload in packet_summaries.items():
        path = Path(payload["packet_root"]) / "trade_level_records.json"
        if not path.exists():
            continue
        trades = read_json(path)
        if not isinstance(trades, list):
            continue
        routed = [row for row in trades if "routed_total" in str(row.get("record_view", "")).lower() or str(row.get("route_role", "")).lower() == "routed_total"]
        selected = routed if routed else trades
        for row in selected:
            when = str(row.get("open_time") or row.get("close_time") or "")
            match = re.match(r"(\d{4})-(\d{2})", when)
            if not match:
                continue
            year, month = int(match.group(1)), int(match.group(2))
            quarter = f"{year}Q{((month - 1) // 3) + 1}"
            split = str(row.get("split") or "unknown")
            key = (run_id, split, quarter)
            bucket = grouped.setdefault(key, {"run_id": run_id, "split": split, "quarter": quarter, "trade_count": 0, "net_profit": 0.0})
            bucket["trade_count"] += 1
            bucket["net_profit"] += float(row.get("net_profit") or 0.0)
    return sorted(grouped.values(), key=lambda row: (row["run_id"], row["split"], row["quarter"]))


def segment_summary(segment_rows: Sequence[Mapping[str, Any]]) -> dict[str, dict[str, Any]]:
    by_run: dict[str, list[Mapping[str, Any]]] = defaultdict(list)
    for row in segment_rows:
        by_run[str(row["run_id"])].append(row)
    summaries: dict[str, dict[str, Any]] = {}
    for run_id, rows in by_run.items():
        positive = sum(1 for row in rows if float(row.get("net_profit") or 0.0) > 0.0)
        summaries[run_id] = {
            "segment_count": len(rows),
            "positive_segment_count": positive,
            "quarter_positive_rate": positive / len(rows) if rows else None,
            "min_segment_trades": min(int(row.get("trade_count") or 0) for row in rows) if rows else 0,
        }
    return summaries


def build_run_index(packet_summaries: Mapping[str, Mapping[str, Any]], segment_by_run: Mapping[str, Mapping[str, Any]]) -> list[dict[str, Any]]:
    registry_rows = [row for row in read_csv_rows(RUN_REGISTRY_PATH) if in_scope_stage(str(row.get("stage_id") or ""))]
    seen = {str(row.get("run_id")) for row in registry_rows}
    for run_id, payload in packet_summaries.items():
        summary = payload["summary"]
        stage_id = str(summary.get("stage_id") or "")
        if run_id not in seen and in_scope_stage(stage_id):
            registry_rows.append({"run_id": run_id, "stage_id": stage_id, "lane": "packet_summary", "status": summary.get("status", ""), "judgment": summary.get("judgment", ""), "path": rel(payload["packet_root"]), "notes": summary.get("boundary", "")})
            seen.add(run_id)

    rows: list[dict[str, Any]] = []
    for source in registry_rows:
        run_id = str(source.get("run_id") or "")
        summary_payload = packet_summaries.get(run_id, {})
        summary = summary_payload.get("summary", {}) if isinstance(summary_payload, Mapping) else {}
        stage_id = str(source.get("stage_id") or summary.get("stage_id") or "")
        text = text_blob(run_id, stage_id, source.get("lane"), source.get("status"), source.get("judgment"), source.get("notes"), summary.get("model_family"), summary.get("topic_read"), summary.get("boundary"))
        onnx_seen = "onnx" in json.dumps(json_ready(summary.get("model_artifacts", {})), ensure_ascii=False).lower()
        roles = derive_roles(text)
        validation = routed_metrics(summary, "validation_routed")
        oos = routed_metrics(summary, "oos_routed")
        seg = segment_by_run.get(run_id, {})
        has_segments = bool(seg.get("segment_count"))
        row = {
            "run_id": run_id,
            "stage_id": stage_id,
            "stage_number": stage_number(stage_id) or "",
            "source_kind": "run_registry_plus_packet_summary" if summary else "run_registry",
            "source_path": str(source.get("path") or rel(summary_payload.get("packet_root", Path()))),
            "status": str(source.get("status") or summary.get("status") or ""),
            "judgment": str(source.get("judgment") or summary.get("judgment") or summary.get("closure_judgment") or ""),
            "external_verification_status": str(summary.get("external_verification_status") or source.get("external_verification_status") or ""),
            "roles": "|".join(roles),
            "mechanism_class": mechanism_class(roles, text, onnx_seen),
            "validation_net_profit": metric(validation, "net_profit"),
            "validation_profit_factor": metric(validation, "profit_factor"),
            "validation_trades": metric(validation, "trade_count", "deal_count"),
            "oos_net_profit": metric(oos, "net_profit"),
            "oos_profit_factor": metric(oos, "profit_factor"),
            "oos_trades": metric(oos, "trade_count", "deal_count"),
            "has_trade_segments": has_segments,
            "quarter_positive_rate": seg.get("quarter_positive_rate"),
            "candidate_status": "",
            "candidate_reason": "",
            "claim_boundary": BOUNDARY,
        }
        row["candidate_status"], row["candidate_reason"] = classify_candidate(row, text)
        rows.append(row)
    return rows


def classify_candidate(row: Mapping[str, Any], blob: str) -> tuple[str, str]:
    number = int(row.get("stage_number") or 0)
    val_net = safe_float(row.get("validation_net_profit"))
    oos_net = safe_float(row.get("oos_net_profit"))
    val_pf = safe_float(row.get("validation_profit_factor"))
    oos_pf = safe_float(row.get("oos_profit_factor"))
    val_trades = safe_float(row.get("validation_trades")) or 0.0
    oos_trades = safe_float(row.get("oos_trades")) or 0.0
    q_rate = safe_float(row.get("quarter_positive_rate"))
    if number < 20:
        return "deferred", "pre_stage20_context_preserved_not_adapter_candidate"
    if row.get("external_verification_status") != "completed":
        return "deferred", "external_runtime_verification_missing_or_not_completed"
    if None in (val_net, oos_net, val_pf, oos_pf):
        return "deferred", "validation_oos_routed_metrics_missing"
    if val_net <= 0.0 and oos_net > 0.0:
        return "negative_memory", "validation_oos_inversion_not_promotable"
    if min(val_trades, oos_trades) < 30 and max(val_pf or 0.0, oos_pf or 0.0) > 1.2:
        return "negative_memory", "tiny_trade_count_pf_spike_risk"
    if val_net > 0.0 and oos_net > 0.0 and val_pf >= 1.0 and oos_pf >= 1.0 and q_rate is not None and q_rate >= 0.5:
        if re.search(r"invalid|blocked|negative", blob):
            return "deferred", "positive_metrics_but_negative_or_blocked_boundary_present"
        return "adapter_candidate", "validation_oos_positive_with_segment_repeatability_floor"
    return "deferred", "readiness_floor_not_met"


