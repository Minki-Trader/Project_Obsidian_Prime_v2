def utc_now() -> str:
    return datetime.now(UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def rel(path: Path) -> str:
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def read_json(path: Path) -> Any:
    return json.loads(io_path(path).read_text(encoding="utf-8-sig"))


def write_json(path: Path, payload: Any) -> None:
    io_path(path.parent).mkdir(parents=True, exist_ok=True)
    io_path(path).write_text(json.dumps(json_ready(payload), ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def write_md(path: Path, text: str) -> None:
    io_path(path.parent).mkdir(parents=True, exist_ok=True)
    io_path(path).write_text(text.rstrip() + "\n", encoding="utf-8-sig")


def write_csv(path: Path, columns: Sequence[str], rows: Sequence[Mapping[str, Any]]) -> None:
    io_path(path.parent).mkdir(parents=True, exist_ok=True)
    with io_path(path).open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(columns), lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow({column: json_ready(row.get(column, "")) for column in columns})


def stage_number(stage_id: str) -> int | None:
    match = re.match(r"^(\d+)_", str(stage_id))
    return int(match.group(1)) if match else None


def in_scope_stage(stage_id: str) -> bool:
    number = stage_number(stage_id)
    return number is not None and 10 <= number <= 32


def safe_float(value: Any) -> float | None:
    if value in (None, "", "NA"):
        return None
    if isinstance(value, Mapping) and "value" in value:
        return safe_float(value.get("value"))
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def metric(metrics: Mapping[str, Any], *names: str) -> float | None:
    for name in names:
        value = safe_float(metrics.get(name))
        if value is not None:
            return value
    return None


def packet_run_id(packet_id: str, summary: Mapping[str, Any] | None = None) -> str:
    if summary:
        for key in ("run_id", "current_run_id", "source_run_id"):
            value = summary.get(key)
            if isinstance(value, str) and value.startswith("run"):
                return value
    match = re.search(r"(run\d+[A-Z]*_[a-z0-9_]+_v\d+)", packet_id, flags=re.IGNORECASE)
    return match.group(1) if match else packet_id


