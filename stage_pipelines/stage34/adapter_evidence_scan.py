def role_map(index_rows: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    result = {role: {"run_count": 0, "candidate_count": 0, "runs": []} for role in ROLES}
    for row in index_rows:
        for role in str(row.get("roles") or "").split("|"):
            if role not in result:
                continue
            result[role]["run_count"] += 1
            if row.get("candidate_status") == "adapter_candidate":
                result[role]["candidate_count"] += 1
            result[role]["runs"].append(str(row["run_id"]))
    return result


def onnx_decision(candidates: Sequence[Mapping[str, Any]], packet_summaries: Mapping[str, Mapping[str, Any]]) -> dict[str, Any]:
    source_seen: list[str] = []
    for row in candidates:
        summary = packet_summaries.get(str(row["run_id"]), {}).get("summary", {})
        if "onnx" in json.dumps(json_ready(summary.get("model_artifacts", {})), ensure_ascii=False).lower():
            source_seen.append(str(row["run_id"]))
    return {
        "decision": "not_ready_for_new_onnx_artifact",
        "existing_onnx_source_observed_for_candidates": source_seen,
        "new_onnx_artifacts_generated": False,
        "reason": "Candidate behavior is not yet stabilized as an adapter contract across repeatability and runtime handoff gates.",
        "readiness_gate": {
            "role_clear": bool(candidates),
            "input_contract_fixed": False,
            "output_contract_fixed": False,
            "python_onnx_parity_plan": "required_before_export",
            "mt5_handoff_plan": "required_before_runtime_claim",
            "runtime_advantage_over_score_table_or_mql": "not_established",
        },
        "claim_boundary": BOUNDARY,
    }


